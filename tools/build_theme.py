#!/usr/bin/env python3
"""Build the Kaltsit Xcursor theme deterministically from the original ANI files."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import shutil
import tempfile

from cursorlib import load_cursor
from xcursor import write_xcursor, read_headers

ROOT = Path(__file__).resolve().parent.parent
SIZES = [24, 32, 48, 64, 96]
MARKER = ".kaltsit-generated"


def build(output: Path, sizes: list[int]) -> dict:
    output = output.absolute()
    if output.is_symlink():
        raise ValueError("output must not be a symlink")
    if output.exists() and (not output.is_dir() or not (output / MARKER).is_file()):
        raise ValueError(f"refusing to replace a directory not generated by this tool: {output}")
    if not sizes or any(not 1 <= size <= 256 for size in sizes):
        raise ValueError("sizes must be between 1 and 256 pixels")
    sizes = sorted(set(sizes))
    manifest = json.loads((ROOT / "cursors.json").read_text())
    names = set()
    for name, spec in manifest.items():
        for entry in [name, *spec["aliases"]]:
            if not entry or Path(entry).name != entry or entry in {".", ".."} or entry in names:
                raise ValueError(f"duplicate or invalid cursor name: {entry}")
            names.add(entry)
        if Path(spec["source"]).name != spec["source"]:
            raise ValueError("source must be a filename")
        if not (ROOT / "assets/windows" / spec["source"]).is_file():
            raise ValueError(f"missing source: {spec['source']}")
    output.parent.mkdir(parents=True, exist_ok=True)
    report = {"theme": "Kaltsit", "sizes": sizes, "cursors": {}}
    with tempfile.TemporaryDirectory(prefix=".kaltsit-build-", dir=output.parent) as temp:
        stage = Path(temp) / "Kaltsit"
        cursors = stage / "cursors"
        cursors.mkdir(parents=True)
        for name, spec in manifest.items():
            source = ROOT / "assets/windows" / spec["source"]
            frames = {size: load_cursor(source, size) for size in sizes}
            write_xcursor(cursors / name, frames)
            headers = read_headers(cursors / name)
            for alias in spec["aliases"]:
                (cursors / alias).symlink_to(name)
            report["cursors"][name] = {
                "source": spec["source"],
                "source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
                "frames_per_size": len(frames[sizes[0]]),
                "duration_ms": sum(f.delay_ms for f in frames[sizes[0]]),
                "aliases": spec["aliases"],
                "images": [{k: h[k] for k in ("size", "width", "height", "xhot", "yhot", "delay_ms")} for h in headers],
            }
        (stage / "index.theme").write_text(
            "[Icon Theme]\nName=Kaltsit\nName[zh_CN]=凯尔希 · 思衡托\n"
            "Comment=Animated Kal'tsit cursors, adapted from the Windows theme\n"
            "Inherits=Adwaita,hicolor\n", encoding="utf-8")
        (stage / MARKER).write_text("Generated by kaltsit-cursors/tools/build_theme.py\n")
        (stage / "build-report.json").write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n")
        for name in ("LICENSE", "LICENSE-MIT", "CREDITS.md"):
            if (ROOT / name).is_file():
                shutil.copyfile(ROOT / name, stage / name)
        if output.exists():
            shutil.rmtree(output)
        stage.rename(output)
    print(f"Built {len(manifest)} animated cursors, {len(names) - len(manifest)} aliases, sizes {sizes}: {output}")
    return report


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "theme/Kaltsit")
    parser.add_argument("--sizes", type=int, nargs="+", default=SIZES)
    args = parser.parse_args()
    try:
        build(args.output, args.sizes)
    except (ValueError, OSError) as exc:
        parser.exit(1, f"build failed: {exc}\n")


if __name__ == "__main__":
    main()
